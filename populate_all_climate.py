def populate_all():
    wb = openpyxl.load_workbook(WORKBOOK)
    ws = wb.active

    headers = {cell.value: cell.column for cell in ws[1] if cell.value is not None}
    next_col = ws.max_column + 1

    # Ensure all climate headers exist
    all_climate_cols = (
        [f"{m} High (C)" for m in MONTHS] +
        [f"{m} Low (C)"  for m in MONTHS] +
        [f"{m} Rainy Days" for m in MONTHS] +
        [f"{m} Rain (mm)" for m in MONTHS] +
        [f"{m} AQI"      for m in MONTHS]
    )
    for col_name in all_climate_cols:
        if col_name not in headers:
            ws.cell(row=1, column=next_col, value=col_name)
            headers[col_name] = next_col
            next_col += 1

    dest_col = headers.get("Destination", 1)

    updated_count = 0
    for r in range(2, ws.max_row + 1):
        dest = ws.cell(row=r, column=dest_col).value
        if not dest or str(dest).strip() == "":
            continue

        dest_clean = str(dest).strip()
        
        # Check if we have data for this destination
        if dest_clean in ALL_REMAINING_CLIMATE:
            cdata = ALL_REMAINING_CLIMATE[dest_clean]
            
            # Map high
            for i, m in enumerate(MONTHS):
                ws.cell(row=r, column=headers[f"{m} High (C)"], value=cdata["High"][i])
                ws.cell(row=r, column=headers[f"{m} Low (C)"],  value=cdata["Low"][i])
                ws.cell(row=r, column=headers[f"{m} Rainy Days"], value=cdata["RainyDays"][i])
                ws.cell(row=r, column=headers[f"{m} Rain (mm)"], value=cdata["Rain"][i])
                ws.cell(row=r, column=headers[f"{m} AQI"],      value=cdata["AQI"][i])
            
            updated_count += 1
            print(f"Populated Row {r}: {dest_clean}")

    wb.save(WORKBOOK)
    wb.close()
    print(f"\n[SUCCESS] Populated climate data for {updated_count} destination rows.")


if __name__ == "__main__":
    populate_all()
